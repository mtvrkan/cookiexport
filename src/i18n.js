let _lang = 'en'

function t(key) {
  return T[_lang]?.[key] ?? T.en[key] ?? key
}

async function initI18n() {
  const s = await chrome.storage.local.get('lang')
  _lang = s.lang || navigator.language?.slice(0, 2) || 'en'
  if (!T[_lang]) _lang = 'en'
  applyDir()
}

function setLang(code) {
  _lang = T[code] ? code : 'en'
  applyDir()
}

function getLang() { return _lang }

function applyDir() {
  const langObj = LANGS.find(l => l.code === _lang)
  document.documentElement.dir = langObj?.dir || 'ltr'
  // Keep the document language honest — screen readers pick their voice from it.
  document.documentElement.lang = _lang
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n
    if (el.tagName === 'INPUT' && el.type !== 'checkbox') {
      el.placeholder = t(key)
    } else {
      el.textContent = t(key)
    }
  })
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPh)
  })
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.dataset.i18nTitle)
  })
  // Icon-only controls carry no text, so their accessible name comes from here.
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria))
  })
}
